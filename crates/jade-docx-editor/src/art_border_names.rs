/// The schema's spelling of the art border named `name` (case-insensitive),
/// or `None` for a line style.
pub(crate) fn art_border_name(name: &str) -> Option<&'static str> {
    ART_BORDER_NAMES
        .iter()
        .find(|art| art.eq_ignore_ascii_case(name))
        .copied()
}
