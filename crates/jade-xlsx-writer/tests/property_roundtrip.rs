//! Property tests over the writer: whatever the edit and whatever the sheet's
//! XML shape, reading the written bytes back gives exactly the edited values,
//! the untouched cells keep theirs, and every part the write had no business
//! in comes back byte for byte.

mod common;

use std::collections::BTreeMap;

use common::workbook_with_sheet;
use jade_opc::OpcPackage;
use jade_xlsx_reader::{read_xlsx, CellRef, CellValue};
use jade_xlsx_writer::{write_xlsx, CellEdit, NewValue, SheetEdits};
use proptest::prelude::*;

const SHEET: &str = "xl/worksheets/sheet1.xml";

/// A dense base grid the sheet part starts from.
fn base_grid() -> impl Strategy<Value = (u32, u32)> {
    (1u32..=4, 1u32..=4)
}

fn finite_number() -> impl Strategy<Value = f64> {
    prop_oneof![
        any::<f64>().prop_filter("finite", |value| value.is_finite()),
        (-1_000_000i64..1_000_000).prop_map(|value| value as f64),
    ]
}

/// Any Rust string, control characters and all — SpreadsheetML's `_xHHHH_`
/// escape has to carry every one of them through XML, a carriage return and a
/// literal `_x000A_` included.
fn arbitrary_text() -> impl Strategy<Value = String> {
    prop_oneof![
        prop::collection::vec(any::<char>(), 0..12).prop_map(String::from_iter),
        Just("line1\r\nline2".to_string()),
        Just("_x000A_ stays literal".to_string()),
    ]
}

/// Formula text stays printable — a control character in a formula is not a
/// formula — but includes everything XML itself trips over.
fn formula_text() -> impl Strategy<Value = String> {
    proptest::string::string_regex("[A-Z]{1,3}[A-Za-z0-9 ():+*/<>&\"'$!,._-]{0,20}").expect("regex")
}

fn new_value() -> impl Strategy<Value = NewValue> {
    prop_oneof![
        finite_number().prop_map(NewValue::Number),
        arbitrary_text().prop_map(NewValue::Text),
        any::<bool>().prop_map(NewValue::Bool),
        formula_text().prop_map(NewValue::Formula),
        Just(NewValue::Blank),
    ]
}

fn edits() -> impl Strategy<Value = Vec<(u32, u32, NewValue)>> {
    prop::collection::vec((0u32..7, 0u32..7, new_value()), 1..8)
}

/// The base sheet as XML, with every reference written out, or with rows and
/// cells left unnumbered the way streaming producers write them.
fn sheet_xml(rows: u32, columns: u32, implicit: bool) -> String {
    let mut xml = String::from(
        r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>"#,
    );
    for row in 0..rows {
        if implicit {
            xml.push_str("<row>");
        } else {
            xml.push_str(&format!("<row r=\"{}\">", row + 1));
        }
        for column in 0..columns {
            let value = base_value(row, column);
            if implicit {
                xml.push_str(&format!("<c><v>{value}</v></c>"));
            } else {
                let reference = reference_text(CellRef::new(column, row));
                xml.push_str(&format!("<c r=\"{reference}\"><v>{value}</v></c>"));
            }
        }
        xml.push_str("</row>");
    }
    xml.push_str("</sheetData></worksheet>");
    xml
}

fn base_value(row: u32, column: u32) -> u32 {
    row * 100 + column + 1
}

fn reference_text(reference: CellRef) -> String {
    let mut label = Vec::new();
    let mut remaining = u64::from(reference.column) + 1;
    while remaining > 0 {
        label.push(b'A' + ((remaining - 1) % 26) as u8);
        remaining = (remaining - 1) / 26;
    }
    label.reverse();
    format!(
        "{}{}",
        String::from_utf8(label).expect("ASCII"),
        reference.row + 1
    )
}

fn expected_value(value: &NewValue) -> CellValue {
    match value {
        NewValue::Number(number) => CellValue::Number(*number),
        NewValue::Text(text) if text.is_empty() => CellValue::Empty,
        NewValue::Text(text) => CellValue::Text(text.clone()),
        NewValue::Bool(flag) => CellValue::Bool(*flag),
        NewValue::Formula(_) | NewValue::Blank => CellValue::Empty,
        // Never generated by `new_value()`; `check_styles` handles it itself.
        NewValue::Unchanged
        | NewValue::FormulaCached { .. }
        | NewValue::Error(_)
        | NewValue::Remove => unreachable!("this generator produces ordinary value edits"),
    }
}

fn cell_of(sheet: &jade_xlsx_reader::Sheet, reference: CellRef) -> Option<&jade_xlsx_reader::Cell> {
    sheet
        .rows
        .iter()
        .find(|row| row.index == reference.row)?
        .cells
        .iter()
        .find(|cell| cell.reference == reference)
}

fn check_roundtrip(rows: u32, columns: u32, implicit: bool, edits: Vec<(u32, u32, NewValue)>) {
    let original = workbook_with_sheet(&sheet_xml(rows, columns, implicit));

    // Last write wins when one batch names a cell twice, which is what the
    // patcher's pending map does; the expectation mirrors it.
    let mut last: BTreeMap<CellRef, NewValue> = BTreeMap::new();
    for (row, column, value) in &edits {
        last.insert(CellRef::new(*column, *row), value.clone());
    }
    let cells: Vec<CellEdit> = edits
        .iter()
        .map(|(row, column, value)| CellEdit {
            reference: CellRef::new(*column, *row),
            value: value.clone(),
            style_index: None,
        })
        .collect();

    let written = write_xlsx(
        &original,
        &[SheetEdits {
            part_name: SHEET.to_string(),
            cells,
        }],
    )
    .expect("write");
    let workbook = read_xlsx(&written).expect("read back");
    let sheet = &workbook.sheets[0];

    for (reference, value) in &last {
        let cell = cell_of(sheet, *reference);
        let read = cell
            .map(|cell| cell.value.clone())
            .unwrap_or(CellValue::Empty);
        assert_eq!(
            read,
            expected_value(value),
            "{} after {value:?}",
            reference_text(*reference)
        );
        if let NewValue::Formula(formula) = value {
            assert_eq!(
                cell.and_then(|cell| cell.formula.as_deref()),
                Some(formula.as_str()),
                "formula at {}",
                reference_text(*reference)
            );
        }
    }

    for row in 0..rows {
        for column in 0..columns {
            let reference = CellRef::new(column, row);
            if last.contains_key(&reference) {
                continue;
            }
            assert_eq!(
                cell_of(sheet, reference).map(|cell| cell.value.clone()),
                Some(CellValue::Number(f64::from(base_value(row, column)))),
                "untouched {} moved",
                reference_text(reference)
            );
        }
    }

    let before = OpcPackage::open(&original).expect("before");
    let after = OpcPackage::open(&written).expect("after");
    assert_eq!(before.part_names(), after.part_names());
    for name in before.part_names() {
        if name == SHEET || name == "xl/workbook.xml" {
            continue;
        }
        assert_eq!(before.part(name), after.part(name), "{name} changed");
    }
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(64))]

    #[test]
    fn any_edit_reads_back_from_an_explicitly_referenced_sheet(
        (rows, columns) in base_grid(),
        edits in edits(),
    ) {
        check_roundtrip(rows, columns, false, edits);
    }

    #[test]
    fn any_edit_reads_back_from_a_sheet_that_omits_references(
        (rows, columns) in base_grid(),
        edits in edits(),
    ) {
        check_roundtrip(rows, columns, true, edits);
    }

    #[test]
    fn a_cell_reference_survives_formatting_and_parsing(
        column in 0u32..=16_383,
        row in 0u32..=1_048_575,
    ) {
        let reference = CellRef::new(column, row);
        let parsed = CellRef::parse(&reference_text(reference)).expect("parse");
        prop_assert_eq!(parsed, reference);
    }

    #[test]
    fn parsing_an_arbitrary_string_never_panics(input in ".{0,12}") {
        let _ = CellRef::parse(&input);
        let _ = jade_xlsx_reader::CellRange::parse(&input);
    }
}

/// A style index on any edit — a value, a blank, or an unchanged cell — reads
/// back as the cell's style, and an unchanged cell keeps the value it had.
fn check_styles(rows: u32, columns: u32, edits: Vec<(u32, u32, Option<NewValue>, u32)>) {
    let original = workbook_with_sheet(&sheet_xml(rows, columns, false));
    let mut last: BTreeMap<CellRef, (Option<NewValue>, u32)> = BTreeMap::new();
    for (row, column, value, style) in &edits {
        last.insert(CellRef::new(*column, *row), (value.clone(), *style));
    }
    let cells = edits
        .iter()
        .map(|(row, column, value, style)| CellEdit {
            reference: CellRef::new(*column, *row),
            value: value.clone().unwrap_or(NewValue::Unchanged),
            style_index: Some(*style),
        })
        .collect::<Vec<_>>();
    let written = write_xlsx(
        &original,
        &[SheetEdits {
            part_name: SHEET.to_string(),
            cells,
        }],
    )
    .expect("write");
    let workbook = read_xlsx(&written).expect("read back");
    let sheet = &workbook.sheets[0];
    for (reference, (value, style)) in &last {
        let cell = cell_of(sheet, *reference).expect("a styled cell exists");
        assert_eq!(
            cell.style_index,
            Some(*style),
            "style at {}",
            reference_text(*reference)
        );
        let expected = match value {
            Some(value) => expected_value(value),
            None if reference.row < rows && reference.column < columns => {
                CellValue::Number(f64::from(base_value(reference.row, reference.column)))
            }
            None => CellValue::Empty,
        };
        assert_eq!(
            cell.value,
            expected,
            "value at {}",
            reference_text(*reference)
        );
    }
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(64))]

    #[test]
    fn any_style_index_reads_back_and_an_unchanged_cell_keeps_its_value(
        (rows, columns) in base_grid(),
        edits in prop::collection::vec(
            (0u32..8, 0u32..8, prop::option::of(new_value()), 0u32..12),
            1..8,
        ),
    ) {
        check_styles(rows, columns, edits);
    }
}
