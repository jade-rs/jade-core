pub(super) fn pair_units(style: usize, left: u8, right: u8) -> Option<i16> {
    if !(b' '..=b'~').contains(&left) || !(b' '..=b'~').contains(&right) {
        return None;
    }
    let pairs = match style {
        1 => STYLE_1,
        2 => STYLE_2,
        3 => STYLE_3,
        _ => return None,
    };
    let key = (u16::from(left) << 8) | u16::from(right);
    Some(
        pairs
            .binary_search_by_key(&key, |(pair, _)| *pair)
            .map_or(0, |index| pairs[index].1),
    )
}
