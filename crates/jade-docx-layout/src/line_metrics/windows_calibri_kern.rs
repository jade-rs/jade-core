pub(super) fn pair_units(left: u8, right: u8) -> Option<i16> {
    if !(b' '..=b'~').contains(&left) || !(b' '..=b'~').contains(&right) {
        return None;
    }
    let key = (u16::from(left) << 8) | u16::from(right);
    Some(
        WINDOWS_CALIBRI_REGULAR_PAIR_UNITS
            .binary_search_by_key(&key, |(pair, _)| *pair)
            .map_or(0, |index| WINDOWS_CALIBRI_REGULAR_PAIR_UNITS[index].1),
    )
}
